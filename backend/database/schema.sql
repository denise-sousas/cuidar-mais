CREATE TABLE IF NOT EXISTS usuarios (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome          VARCHAR(100) NOT NULL,
  email         VARCHAR(150) NOT NULL UNIQUE,
  cpf           VARCHAR(14) UNIQUE,
  senha_hash    VARCHAR(255) NOT NULL,
  perfil        VARCHAR(20) NOT NULL CHECK (perfil IN ('administrador','cuidador','familiar')),
  ativo         SMALLINT NOT NULL DEFAULT 1 CHECK (ativo IN (0, 1)),
  criado_em     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS idosos (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome            VARCHAR(100) NOT NULL,
  data_nascimento DATE NOT NULL,
  cpf             VARCHAR(14) UNIQUE,
  telefone        VARCHAR(20),
  endereco        VARCHAR(255),
  observacoes     TEXT,
  codigo_vinculo  VARCHAR(20) NOT NULL UNIQUE,
  criado_por      INTEGER NOT NULL REFERENCES usuarios(id),
  criado_em       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS vinculos (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  idoso_id   INTEGER NOT NULL REFERENCES idosos(id) ON DELETE CASCADE,
  papel      VARCHAR(20) NOT NULL CHECK (papel IN ('cuidador','familiar')),
  criado_em  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (usuario_id, idoso_id)
);
CREATE INDEX IF NOT EXISTS idx_vinculos_idoso ON vinculos(idoso_id);

CREATE TABLE IF NOT EXISTS convites_familiares (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idoso_id   INTEGER NOT NULL REFERENCES idosos(id) ON DELETE CASCADE,
  email      VARCHAR(150) NOT NULL,
  criado_por INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  criado_em  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (idoso_id, email)
);
CREATE INDEX IF NOT EXISTS idx_convites_email ON convites_familiares(email);

CREATE TABLE IF NOT EXISTS medicamentos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idoso_id    INTEGER NOT NULL REFERENCES idosos(id) ON DELETE CASCADE,
  nome        VARCHAR(100) NOT NULL,
  dosagem     VARCHAR(50),
  via         VARCHAR(50),
  observacoes TEXT,
  ativo       SMALLINT NOT NULL DEFAULT 1 CHECK (ativo IN (0, 1)),
  criado_em   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_medicamentos_idoso ON medicamentos(idoso_id);

CREATE TABLE IF NOT EXISTS horarios_medicamento (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medicamento_id INTEGER NOT NULL REFERENCES medicamentos(id) ON DELETE CASCADE,
  horario        TIME NOT NULL,
  UNIQUE (medicamento_id, horario)
);

CREATE TABLE IF NOT EXISTS administracoes_medicamento (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idoso_id        INTEGER NOT NULL REFERENCES idosos(id) ON DELETE CASCADE,
  medicamento_id  INTEGER NOT NULL REFERENCES medicamentos(id) ON DELETE CASCADE,
  horario         TIME NOT NULL,
  data            DATE NOT NULL,
  administrado_em TIMESTAMP NOT NULL,
  usuario_id      INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  UNIQUE (medicamento_id, horario, data)
);
CREATE INDEX IF NOT EXISTS idx_administracoes_idoso ON administracoes_medicamento(idoso_id, data);

CREATE TABLE IF NOT EXISTS cuidados (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idoso_id      INTEGER NOT NULL REFERENCES idosos(id) ON DELETE CASCADE,
  titulo        VARCHAR(100) NOT NULL,
  descricao     VARCHAR(255),
  tipo          VARCHAR(30) NOT NULL DEFAULT 'outro' CHECK (tipo IN ('higiene','alimentacao','hidratacao','atividade_fisica','sono','outro')),
  data          DATE NOT NULL,
  horario       TIME NOT NULL,
  concluido     SMALLINT NOT NULL DEFAULT 0 CHECK (concluido IN (0, 1)),
  concluido_em  TIMESTAMP,
  concluido_por INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  criado_por    INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  criado_em     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cuidados_idoso_data ON cuidados(idoso_id, data);

CREATE TABLE IF NOT EXISTS registros_cuidado (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idoso_id      INTEGER NOT NULL REFERENCES idosos(id) ON DELETE CASCADE,
  tipo          VARCHAR(30) NOT NULL CHECK (tipo IN ('alimentacao','hidratacao','higiene','atividade_fisica','outro')),
  descricao     VARCHAR(255),
  quantidade_ml INTEGER CHECK (quantidade_ml IS NULL OR quantidade_ml >= 0),
  data_hora     TIMESTAMP NOT NULL,
  usuario_id    INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  criado_em     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_registros_idoso_data ON registros_cuidado(idoso_id, data_hora);

CREATE TABLE IF NOT EXISTS consultas (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idoso_id   INTEGER NOT NULL REFERENCES idosos(id) ON DELETE CASCADE,
  titulo     VARCHAR(100) NOT NULL,
  local      VARCHAR(150),
  data       DATE NOT NULL,
  horario    TIME NOT NULL,
  descricao  TEXT,
  realizada  SMALLINT NOT NULL DEFAULT 0 CHECK (realizada IN (0, 1)),
  criado_por INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  criado_em  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_consultas_idoso_data ON consultas(idoso_id, data);

CREATE TABLE IF NOT EXISTS observacoes (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idoso_id   INTEGER NOT NULL REFERENCES idosos(id) ON DELETE CASCADE,
  titulo     VARCHAR(100) NOT NULL,
  categoria  VARCHAR(30) NOT NULL DEFAULT 'outro' CHECK (categoria IN ('saude','comportamento','alimentacao','sono','consulta','outro')),
  texto      TEXT NOT NULL,
  data_hora  TIMESTAMP NOT NULL,
  usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  criado_em  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_observacoes_idoso_data ON observacoes(idoso_id, data_hora);
